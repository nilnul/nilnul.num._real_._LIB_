using System;

namespace nilnul.num.real.bi_
{
	static public class _RootX
	{
		/// <summary>
		/// <see cref=""/>
		/// </summary>
		/// <param name="radicand"></param>
		/// <param name="degree"></param>
		/// <returns>
		///
		/// </returns>
		static public double Root(double radicand, double degree) {
			return Math.Pow( radicand , 1/degree );
		}
	}



}
