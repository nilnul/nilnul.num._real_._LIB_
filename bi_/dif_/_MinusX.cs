namespace nilnul.num.real.bi_
{
	static public class _MinusX
	{
		/// <summary>
		/// name each argument
		/// </summary>
		/// <param name="minuend"></param>
		/// <param name="subtrahend"></param>
		/// <returns>
		/// difference
		/// </returns>
		static public double Minus(
			double minuend
			,
			double subtrahend
		) {
			return minuend - subtrahend;
		}
	}


}
