namespace nilnul.num.real.bi_
{
	/// <summary>
	/// division.
	/// To avoid confusion of dividing or being divided by, we use the term "Per", which is "/".
	/// For DividedBy, <see cref="nilnul.num.bi_._DispendX"/>, which is "\"
	/// </summary>
	/// alias:
	///		per
	///			,vs: <see cref="_PowX"/>
	static public class _PerX
	{
		/// <summary>
		/// <see cref=""/>
		/// </summary>
		/// <param name="dividend"></param>
		/// <param name="divisor"></param>
		/// <returns>
		///
		/// </returns>
		static public double Per(double dividend, double divisor) {
			return dividend / divisor;
		}
	}

}
